#!/bin/bash
# build.sh -- netcat for the Odyssey 2: build/nc.bin, a protocol 2 (APPBANK)
# image -- the fixed half ($400-$7FF) and NPAGES pages of 2K.
#
#   ./build.sh                          the image, dialling the BBS
#   ENDPOINT=N:TCP://host:port/ ./build.sh
#   SPIKE=1 ./build.sh                  the display engine's test pattern
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="${OUT:-$HERE/build}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
NPAGES=2
SPIKE="${SPIKE:-0}"
mkdir -p "$OUT"

python3 "$HERE/tools/checkflags.py" "$HERE"/src/*.inc
python3 "$HERE/tools/mkcharmap.py" "$OUT/charmap.inc"
# The spec, NUL-terminated. A TELNET or SSH spec with no query of its own
# gets the screen's size, which FujiNet offers the host (NAWS).
ENDPOINT="${ENDPOINT:-N:TELNET://bbs.retrocampus.com/}"
case "$ENDPOINT" in
  [Nn]:*) ;;
  *) ENDPOINT="N:$ENDPOINT" ;;
esac
case "$ENDPOINT" in
  *\?*) ;;
  [Nn]:[Tt][Ee][Ll][Nn][Ee][Tt]:*|[Nn]:[Ss][Ss][Hh]:*) ENDPOINT="$ENDPOINT?cols=80&rows=7" ;;
esac
printf '; GENERATED by build.sh -- do not edit.\nu_spec: db "%s",0\n' "$ENDPOINT" > "$OUT/endpoint.inc"
cp "$HERE"/src/*.inc "$HERE/g7000.h" "$HERE/nc.a48" "$OUT/"

parts=""
for p in $(seq 0 $((NPAGES-1))); do
  printf '; GENERATED by build.sh -- do not edit.\nPAGE equ %d\nNPAGES equ %d\nSPIKE equ %d\n' \
    "$p" "$NPAGES" "$SPIKE" > "$OUT/nc_p$p.a48"
  [ -n "${PADN:-}" ] && printf 'PADN equ %d\n' "$PADN" >> "$OUT/nc_p$p.a48"
  printf '    include "nc.a48"\n' >> "$OUT/nc_p$p.a48"
  ( cd "$OUT" && "$ASL" -q -L -U "nc_p$p.a48" \
      && "$P2BIN" "nc_p$p.p" "nc_pg$p.bin" -r 0x800-0xFFF -l 0 >/dev/null \
      && "$P2BIN" "nc_p$p.p" "nc_fx$p.bin" -r 0x400-0x7FF -l 0 >/dev/null )
  python3 "$HERE/tools/checkobj.py" "$OUT/nc_p$p.p"
  python3 "$HERE/tools/checklayout.py" "$OUT/nc_p$p.lst"
  python3 "$HERE/tools/checkmb.py" "$OUT/nc_p$p.lst" >/dev/null
  python3 "$HERE/tools/checkpage.py" "$OUT/nc_p$p.lst"
  # Every page carries the fixed half; they have to be the same bytes.
  cmp -s "$OUT/nc_fx0.bin" "$OUT/nc_fx$p.bin" \
    || { echo "build.sh: page $p assembled a different fixed half" >&2; exit 1; }
  parts="$parts $OUT/nc_pg$p.bin"
done
# The stack is 8 levels and wraps silently: interrupts plus the deepest main
# chain have to fit.
python3 "$HERE/tools/checkstack.py" $(for p in $(seq 0 $((NPAGES-1))); do echo "$OUT/nc_p$p.lst"; done)
cat "$OUT/nc_fx0.bin" $parts > "$OUT/nc.bin"
size=$(wc -c < "$OUT/nc.bin")
[ "$size" -eq $((1024 + 2048 * NPAGES)) ] \
  || { echo "build.sh: nc.bin is $size bytes" >&2; exit 1; }
echo "build/nc.bin: $size bytes, $NPAGES pages"
if [ "$SPIKE" = 1 ]; then echo "  (the SPIKE test pattern)"; fi

#!/usr/bin/env python3
"""mkcharmap.py -- ASCII to the 8244's character generator: build/charmap.inc.

    mkcharmap.py OUT

One byte for each of $20-$7E: the cell value the terminal stores (4 x glyph,
fixed.inc). Lowercase folds to upper case; a few characters the font lacks
borrow a look-alike; anything else is a blank.
"""
import sys

ROM = "0123456789:$ ?LP+WERTUIOQSDFGHJKAZXCVBM.-*%=YN/#"
LOOKALIKE = {",": ".", ";": ":", "_": "-", "|": "I"}
BACKSLASH = 59                  # the font's picture of one
SPACE = ROM.index(" ")


def glyph(code):
    c = chr(code).upper()
    c = LOOKALIKE.get(c, c)
    if c == "\\":
        return BACKSLASH
    return ROM.index(c) if c in ROM else SPACE


def main(out):
    vals = [4 * glyph(c) for c in range(0x20, 0x7F)]
    rows = [", ".join("%3d" % v for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    open(out, "w").write(
        "; GENERATED by tools/mkcharmap.py -- do not edit.\n"
        "; ASCII $20-$7E -> the cell value, 4 x 8244 glyph (o2doc appendix C)\n"
        "charmap:\n" + "".join("    db %s\n" % r for r in rows))


if __name__ == "__main__":
    main(sys.argv[1])
